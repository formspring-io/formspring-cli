import { readFileSync, readdirSync, statSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import { flagNameFor, ResourceCommand, resourceFlags, type ResourceSpec } from '../src/lib/resource-command.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const commandsDir = join(root, 'src/commands')

type OpenApi = { paths: Record<string, Record<string, { parameters?: Array<{ name: string; in: string }> }>> }

const openapi = JSON.parse(readFileSync(join(root, 'schema/openapi.json'), 'utf8')) as OpenApi
const manifest = JSON.parse(readFileSync(join(root, 'schema/cli-commands.json'), 'utf8')) as Array<{
  cli_command: string
  method: string
  path: string
  name: string
  hand_written?: true
}>

function commandFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry)

    return statSync(full).isDirectory() ? commandFiles(full) : full.endsWith('.ts') ? [full] : []
  })
}

const generatedFiles = commandFiles(commandsDir).filter((file) =>
  readFileSync(file, 'utf8').includes('Generated by scaffold-resource-commands'),
)

describe('flagNameFor', () => {
  it('kebab-cases API parameter names', () => {
    expect(flagNameFor('contactImport', 'path')).toBe('contact-import')
    expect(flagNameFor('per_page', 'query')).toBe('per-page')
  })

  it('never shadows the shared flags', () => {
    expect(flagNameFor('token', 'path')).toBe('token-id')
    expect(flagNameFor('output', 'query')).toBe('query-output')
  })
})

describe('resourceFlags', () => {
  const base: ResourceSpec = {
    route: 'api.test',
    method: 'GET',
    path: '/things/{thing}',
    pathParams: [{ name: 'thing', flag: 'thing' }],
    query: [{ name: 'per_page', flag: 'per-page', type: 'integer' }],
    hasBody: false,
    idempotent: false,
    paginated: false,
  }

  it('requires path parameters and adds only what the operation supports', () => {
    const flags = resourceFlags(base)

    expect(flags.thing.required).toBe(true)
    expect(flags['per-page']).toBeDefined()
    expect(flags.data).toBeUndefined()
    expect(flags['idempotency-key']).toBeUndefined()
    expect(flags.all).toBeUndefined()
    expect(flags.output).toBeUndefined()
  })

  it('adds body, idempotency, pagination and download flags when the operation has them', () => {
    const flags = resourceFlags({
      ...base,
      hasBody: true,
      idempotent: true,
      paginated: true,
      download: { contentType: 'application/pdf' },
    })

    expect(Object.keys(flags)).toEqual(expect.arrayContaining(['data', 'stdin', 'idempotency-key', 'all', 'max-pages', 'output', 'force']))
    expect(flags.output.required).toBe(true)
  })

  it('streams text downloads to stdout unless --output is given', () => {
    const flags = resourceFlags({ ...base, download: { contentType: 'text/csv' } })

    expect(flags.output.required).toBe(false)
  })
})

describe('generated resource commands', () => {
  it('generates a substantial set of commands', () => {
    expect(generatedFiles.length).toBeGreaterThan(200)
    expect(manifest.filter((row) => !row.hand_written).length).toBe(generatedFiles.length)
  })

  it('lists a command file for every hand-written stand-in', () => {
    const files = new Set(commandFiles(commandsDir).map((file) => relative(commandsDir, file).replace(/\.ts$/, '')))

    for (const row of manifest.filter((entry) => entry.hand_written)) {
      expect(files, row.cli_command).toContain(row.cli_command.split(' ').join('/'))
    }
  })

  it.each(generatedFiles.map((file) => [relative(commandsDir, file), file]))('%s matches the OpenAPI document', async (_name, file) => {
    const module = (await import(file)) as { default: typeof ResourceCommand }
    const command = module.default
    const spec = command.spec
    const operation = openapi.paths[spec.path]?.[spec.method.toLowerCase()]

    expect(operation, `${spec.method} ${spec.path} is missing from openapi.json`).toBeDefined()

    const placeholders = [...spec.path.matchAll(/\{([^}]+)\}/g)].map((match) => match[1])
    expect(spec.pathParams.map((param) => param.name)).toEqual(placeholders)

    const documentedQuery = new Set(
      [...(openapi.paths[spec.path].parameters ?? []), ...(operation?.parameters ?? [])]
        .filter((param) => param.in === 'query')
        .map((param) => param.name),
    )
    expect(new Set(spec.query.map((param) => param.name))).toEqual(documentedQuery)

    expect(spec.idempotent).toBe((operation?.parameters ?? []).some((param) => param.name === 'Idempotency-Key'))
    expect(command.description).toBeTruthy()
    expect(Object.keys(command.flags)).toEqual(Object.keys(resourceFlags(spec)))
  })
})

